/** The label for {@code key} in {@code lang}, with {name} placeholders filled. Unknown keys show the key. */
export function t(lang, key, params = {}) {
  const table = MESSAGES[lang] ?? MESSAGES.tr;
  const text = table[key] ?? MESSAGES.en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (m, name) => (name in params ? String(params[name]) : m));
}

export function formatDateTime(lang, iso) {
  if (!iso) return '';
  const locale = lang === 'en' ? 'en-GB' : 'tr-TR';
  return new Intl.DateTimeFormat(locale, { dateStyle: 'medium', timeStyle: 'short' }).format(new Date(iso));
}
